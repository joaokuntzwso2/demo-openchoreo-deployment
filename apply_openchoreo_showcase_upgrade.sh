backup() {
  local f="$1"
  [[ -f "$f" ]] || return 0
  mkdir -p "$BACKUP_DIR/$(dirname "$f")"
  cp -p "$f" "$BACKUP_DIR/$f"
}

for f in \
  demo.sh \
  scripts/rancher.sh \
  services/platform-portal/index.html \
  README.md
