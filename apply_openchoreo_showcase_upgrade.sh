#!/usr/bin/env bash
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

REPORT="${SHOWCASE_CAPABILITY_REPORT:-runtime/showcase-capabilities.md}"
mkdir -p "$(dirname "$REPORT")"
: > "$REPORT"

FAILURES=0
WARNINGS=0

emit() {
  printf '%s\n' "$*" | tee -a "$REPORT"
}

pass() {
  emit "- PASS — $*"
}

warn() {
  WARNINGS=$((WARNINGS + 1))
  emit "- WARN — $*"
}

fail() {
  FAILURES=$((FAILURES + 1))
  emit "- FAIL — $*"
}

have() {
  command -v "$1" >/dev/null 2>&1
}

count_resource() {
  local resource="$1"
  local namespace="${2:-}"
  local out

  if [[ -n "$namespace" ]]; then
    out="$(kubectl get "$resource" -n "$namespace" -o name 2>/dev/null || true)"
  else
    out="$(kubectl get "$resource" -A -o name 2>/dev/null || true)"
  fi

  if [[ -z "$out" ]]; then
    printf '0'
  else
    printf '%s\n' "$out" | awk 'NF {n++} END {print n+0}'
  fi
}

object_exists() {
  local resource="$1"
  local name="$2"
  local namespace="${3:-}"

  if [[ -n "$namespace" ]]; then
    kubectl get "$resource" "$name" -n "$namespace" >/dev/null 2>&1
  else
    kubectl get "$resource" "$name" >/dev/null 2>&1
  fi
}

check_count() {
  local label="$1"
  local resource="$2"
  local expected="$3"
  local namespace="${4:-}"
  local actual
  actual="$(count_resource "$resource" "$namespace")"

  if [[ "$actual" == "$expected" ]]; then
    pass "$label: $actual"
  else
    fail "$label: expected $expected, found $actual"
  fi
}

check_object() {
  local label="$1"
  local resource="$2"
  local name="$3"
  local namespace="${4:-}"

  if object_exists "$resource" "$name" "$namespace"; then
    pass "$label: $name"
  else
    fail "$label missing: $name"
  fi
}

